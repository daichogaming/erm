// Builds the small per-set files Active Recall loads (recall/<skill>_<set>.js) and the word
// counts it uses for keyword scoring (recall/docfreq.js), from drillbank.js.
// Run from the repo root after changing drillbank.js:   node tools/build_recall.js
// The word helpers are read from recall.html itself so both always count words the same way.
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const SKILLS = ['inferences', 'central-ideas-and-details', 'command-of-evidence', 'text-structure-and-purpose', 'cross-text-connections', 'words-in-context'];
const KEEP = ['id', 'domain', 'skill', 'difficulty', 'passage', 'passage_lines', 'question', 'choices', 'answer', 'rationale', 'underline', 'underline_segments', 'unusable'];

const page = fs.readFileSync(path.join(ROOT, 'recall.html'), 'utf8');
const grab = name => { const m = new RegExp('function ' + name + '\\([^)]*\\) \\{[\\s\\S]*?\\n\\}', 'm').exec(page); if (!m) throw new Error('missing ' + name); return m[0]; };
const { wordsOf, norm, passageText } = new Function(grab('wordsOf') + '\n' + grab('norm') + '\n' + grab('passageText') + '\nreturn { wordsOf, norm, passageText };')();

const src = fs.readFileSync(path.join(ROOT, 'drillbank.js'), 'utf8');
const BANK = JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1));

// Word counts over the whole bank, exactly as recall.html used to count them.
const df = {}, seen = new Set(); let count = 0;
Object.values(BANK).forEach(list => list.forEach(q => {
  if (seen.has(q.id)) return; seen.add(q.id); count++;
  new Set(wordsOf(passageText(q)).map(norm)).forEach(n => { df[n] = (df[n] || 0) + 1; });
}));

const out = path.join(ROOT, 'recall'); fs.mkdirSync(out, { recursive: true });
for (const f of fs.readdirSync(out)) if (f.endsWith('.js')) fs.unlinkSync(path.join(out, f));
const sets = {};
for (const slug of SKILLS) {
  let n = 1;
  while (BANK[`${slug}_${n}`]) {
    const qs = BANK[`${slug}_${n}`].map(q => Object.fromEntries(KEEP.filter(k => k in q).map(k => [k, q[k]])));
    fs.writeFileSync(path.join(out, `${slug}_${n}.js`), '// Generated by tools/build_recall.js from drillbank.js. Do not edit.\nwindow.RECALL_SET = ' + JSON.stringify(qs) + ';\n');
    n++;
  }
  sets[slug] = n - 1;
}
fs.writeFileSync(path.join(out, 'docfreq.js'), '// Generated by tools/build_recall.js from drillbank.js. Do not edit.\n' +
  'window.RECALL_SETS = ' + JSON.stringify(sets) + ';\nwindow.RECALL_DOC_COUNT = ' + count + ';\nwindow.RECALL_DF = ' + JSON.stringify(df) + ';\n');
console.log('sets', sets, '| passages counted', count, '| words', Object.keys(df).length);
