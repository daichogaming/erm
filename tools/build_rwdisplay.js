// tools/build_rwdisplay.js: writes rw/<module key>.js for every module in questionbank.js and every drill set in
// drillbank.js: the repaired text of each question (passage, tables, underlines, choices) without answers or
// explanations. test.html and drill.html lay these over the question server's copy, which is older.
// Run from the repo root:  node tools/build_rwdisplay.js
const fs = require('fs'), path = require('path');
const load = (f, name) => new Function(fs.readFileSync(f, 'utf8') + ';return ' + name)();
const banks = [load('questionbank.js', 'QUESTION_BANK'), load('drillbank.js', 'DRILL_BANK')];
const KEEP = ['id', 'domain', 'skill', 'difficulty', 'context', 'passage', 'passage_lines', 'question', 'choices', 'underline', 'underline_segments', 'unusable'];
fs.mkdirSync('rw', { recursive: true });
let n = 0;
for (const bank of banks) for (const key of Object.keys(bank)) {
  if (!/^[a-z0-9-]+_[0-9A-Za-z]+$/.test(key)) continue;
  const qs = bank[key].map(q => { const o = {}; KEEP.forEach(k => { if (q[k] !== undefined) o[k] = q[k]; }); return o; });
  fs.writeFileSync(path.join('rw', key + '.js'), '// Generated by tools/build_rwdisplay.js. Do not edit.\n(window.RW_DISPLAY = window.RW_DISPLAY || {})[' + JSON.stringify(key) + '] = ' + JSON.stringify(qs) + ';\n');
  n++;
}
console.log('wrote', n, 'files');
